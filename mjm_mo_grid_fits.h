D lattice_to_real(IdxTy i) const
{
    // Lattice coordinate x = rmin + ih,
    //      y = x + beta * log(rmin)
    D y = rmin + beta*log(rmin) + h*D(i);
    D r, rold;
    if(beta <= y) r = y;
    else r = exp(y/beta);
    // Solve using Newton's method f(r) == 0, where
    //    f(r) = r + beta*log(r/rmin) - x
    //         = r + beta*log(r) - y
    do
    {   rold = r;
        r = r - (r + beta*log(r) - y)/(1. + beta/r);
        if(r <= 0.0)
            r = rold*.5;
    } while(fabs(r - rold)/r > 1.e-13);

    return r;
}



