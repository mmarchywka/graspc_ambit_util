/*
IdxTy N,NP10;
D RNT,H,HP;
D* R; D* RP; D* RPQR;
rnt=1.8e-7, h=.05, hp=0
ETT[i]=eph^(i-1)=exp(h*(i-1)) base 1
r[i]=rnt*(ett[i]-1)
rp[i]=rnt*ett[i]
rpqr[i]=ett[i]/(ett[i]-1)
*/
auto & lat=m_ambit.m_lat;
