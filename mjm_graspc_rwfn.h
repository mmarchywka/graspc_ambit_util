D Integral(const int rpow, const IdxTy flags=0) const 
{
if (R==0) return 0;
const bool dop=!Bit(flags,0);
const bool doq=!Bit(flags,1);
D sum=0;
D rlast=0;
MM_ILOOP(i,n())
{
if (rpow<0) if (R[i]==0) { rlast=0;  continue; } 
D rp=pow(R[i],rpow);
D dr=R[i]-rlast;
rlast=R[i];
D dp=PF[i]; // *rp*dr;
D dq=QF[i]; // *rp*dr;
if (!dop) dp=0;
if (!doq) dq=0; 
sum+=(dp*dp+dq*dq)*rp*dr;
} // i 
return sum;
} // Integral
